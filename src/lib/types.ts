import { z } from "zod";
import { THEMES } from "./photos";

// Accent colours a creator can pick for their page header.
export const ACCENTS = ["violet", "emerald", "rose", "amber", "sky"] as const;
export type Accent = (typeof ACCENTS)[number];

// Suggested product formats. The model may use these or a close variant.
export const PRODUCT_FORMATS = [
  "Ebook",
  "Mini-course",
  "Cohort course",
  "1:1 call",
  "Webinar",
  "Community",
  "Template pack",
  "Guide",
] as const;

export const TONES = ["English", "Hinglish", "Hindi"] as const;
export type Tone = (typeof TONES)[number];

// SuperProfile sells exactly these five kinds of things.
export const PRODUCT_KINDS = ["course", "digital", "membership", "live", "session"] as const;
export type ProductKind = (typeof PRODUCT_KINDS)[number];

export const ProductSchema = z.object({
  title: z.string().min(1).max(90),
  format: z.string().min(1).max(40),
  priceInr: z.coerce.number().int().min(0).max(1_000_000),
  priceRationale: z.string().min(1).max(320),
  description: z.string().min(1).max(700),
  // New fields are optional so links shared before they existed still open.
  highlights: z.array(z.string().min(1).max(80)).max(4).optional().catch(undefined),
  imageTheme: z.enum(THEMES).optional().catch(undefined),
  imageIndex: z.coerce.number().int().min(0).max(999).optional().catch(undefined),
  // Which of SuperProfile's 5 product types this is (drives icon and button).
  kind: z.enum(PRODUCT_KINDS).optional().catch(undefined),
  // Launch offer: priceInr is the offer price, regularPriceInr the real normal
  // price. After offerEndsAt (YYYY-MM-DD) the store shows the regular price.
  regularPriceInr: z.coerce.number().int().min(1).max(1_000_000).optional().catch(undefined),
  offerEndsAt: z.string().regex(/^\d{4}-\d{2}-\d{2}$/).optional().catch(undefined),
});
export type Product = z.infer<typeof ProductSchema>;

export const PROOF_KINDS = ["followers", "experience", "credential", "clients", "other"] as const;
export type ProofKind = (typeof PROOF_KINDS)[number];

export const ProofSchema = z.object({
  kind: z.enum(PROOF_KINDS).catch("other"),
  text: z.string().min(1).max(60),
});
export type Proof = z.infer<typeof ProofSchema>;

export const TestimonialSchema = z.object({
  quote: z.string().min(1).max(280),
  name: z.string().max(60).optional().catch(undefined),
});
export type Testimonial = z.infer<typeof TestimonialSchema>;

export const StorefrontSchema = z.object({
  creatorName: z.string().min(1).max(60),
  tagline: z.string().min(1).max(140),
  bio: z.string().min(1).max(700),
  niche: z.string().min(1).max(60),
  products: z.array(ProductSchema).min(2).max(4),
  accent: z.enum(ACCENTS).catch("violet"),
  // Filled in only when the input was thin/ambiguous, so the creator knows
  // what we assumed and can correct it. Empty string otherwise.
  assumptions: z.string().max(320).catch("").default(""),
  theme: z.enum(THEMES).optional().catch(undefined),
  coverIndex: z.coerce.number().int().min(0).max(999).optional().catch(undefined),
  // Honest social proof for first-time sellers: facts the creator stated
  // (followers, experience, credentials), never invented reviews.
  proof: z.array(ProofSchema).max(4).optional().catch(undefined),
  // Only ever entered by the creator, never generated by the AI.
  testimonial: TestimonialSchema.optional().catch(undefined),
});
export type Storefront = z.infer<typeof StorefrontSchema>;

export type GenerateInput = {
  description: string;
  handle?: string;
  tone?: Tone;
};
